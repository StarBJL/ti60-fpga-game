#!/usr/bin/env python3
"""Convert inspected transparent sprite atlases to immutable RGB565+A8 assets.
Backgrounds keep the independent HD720 sources; this tool touches actors only.
"""
from pathlib import Path
from PIL import Image,ImageOps,ImageDraw
import numpy as np,ctypes,ctypes.util,json,shutil,hashlib
R=Path(__file__).resolve().parents[1];A=R/'assets/v5';S=R/'par/ddr_demo_ti60/embedded_sw/soc/software/standalone/game/src';D=A/'sources';D.mkdir(exist_ok=True)
lib=ctypes.CDLL(ctypes.util.find_library('lz4'));lib.LZ4_compressBound.argtypes=[ctypes.c_int];lib.LZ4_compress_HC.argtypes=[ctypes.c_void_p,ctypes.c_void_p,ctypes.c_int,ctypes.c_int,ctypes.c_int]
meta=[];pixels=[];alphas=[];tiles=[];offset=0
for e in json.loads((A/'generation.json').read_text()):
 key=e['key'];source=D/(key+'.png')
 if not source.exists():shutil.copy2(e['source'],source)
 im=Image.open(source).convert('RGBA');w,h=im.size
 assert np.asarray(im)[:,:,3].min()==0, f'{key} must have alpha'
 rows=3 if key=='heroes' else 2
 for row in range(rows):
  y0,y1=round(h*row/rows),round(h*(row+1)/rows)
  if key=='ultimate':y0,y1=(0,round(h*.473)) if row==0 else (round(h*.48),h)
  band=np.asarray(im)[y0:y1,:,3];ink=(band>100).sum(axis=0)
  # Locate transparent gutters in the inspected layout rather than assume an
  # AI-generated boss has exactly the same column width as a small creature.
  cuts=[0]
  ranges=[(.20,.28),(.43,.53),(.67,.77)] if key!='heroes' else[(.24,.28),(.49,.53),(.73,.77)]
  for lo,hi in ranges:
   a,b=round(lo*w),round(hi*w);score=np.convolve(ink,np.ones(5),mode='same');cuts.append(int(a+np.argmin(score[a:b])))
  cuts.append(w)
  for col in range(4):
   box=(cuts[col],y0,cuts[col+1],y1);tile=im.crop(box);bbox=tile.getchannel('A').point(lambda a:255 if a>70 else 0).getbbox();assert bbox
   tile=tile.crop(bbox)
   size=(60,60) if key=='heroes' else (144,144) if key=='ultimate' else [(48,56),(48,56),(64,72),(112,112)][col]
   t=Image.new('RGBA',size);f=ImageOps.contain(tile,(size[0]-4,size[1]-4),Image.Resampling.LANCZOS);t.alpha_composite(f,((size[0]-f.width)//2,size[1]-f.height-2))
   ar=np.asarray(t);rgb=ar[:,:,:3].astype(np.uint16);px=(((rgb[:,:,0]>>3)<<11)|((rgb[:,:,1]>>2)<<5)|(rgb[:,:,2]>>3)).astype('<u2');px[ar[:,:,3]==0]=0xf81f
   entry=dict(key=key,row=row,col=col,width=size[0],height=size[1],offset=offset,source_box=box,source_alpha_bbox=bbox)
   meta.append(entry);offset+=size[0]*size[1];pixels.append(px.tobytes());alphas.append(ar[:,:,3].tobytes());tiles.append((entry,t))
raw=b''.join(pixels)+b''.join(alphas);buf=ctypes.create_string_buffer(lib.LZ4_compressBound(len(raw)));n=lib.LZ4_compress_HC(raw,buf,len(raw),len(buf),12);assert n>0;data=buf.raw[:n]
(A/'sprites.raw').write_bytes(raw);(A/'sprites.lz4').write_bytes(data)
c=['/* Generated by tools/build_v5_art.py; RGB565 plus original A8. */','#include "v5_art.h"','#ifdef __riscv','#define PACKED __attribute__((section(".bg_assets"),aligned(64)))','#else','#define PACKED __attribute__((aligned(64)))','#endif','const unsigned v5_sprite_size=%d;'%n,'const unsigned v5_sprite_pixels=%d;'%offset,'const unsigned v5_sprite_bytes=%d;'%len(raw),'const unsigned v5_sprite_count=%d;'%len(meta),'const unsigned v5_sprite_meta[][3]={']
c += ['{%d,%d,%d},'%(m['width'],m['height'],m['offset']) for m in meta];c+=['};','const unsigned char v5_sprite_packed[] PACKED={'];c += [','.join(map(str,data[i:i+32]))+',' for i in range(0,n,32)];c+=['};'];(S/'v5_art_data.c').write_text('\n'.join(c)+'\n')
(S/'v5_art_sizes.h').write_text('#define V5_ART_BYTES %d\n#define V5_ART_COUNT %d\n'%(len(raw),len(meta)))
(A/'sprite_manifest.json').write_text(json.dumps(dict(raw_bytes=len(raw),packed_bytes=n,raw_sha256=hashlib.sha256(raw).hexdigest(),sprites=meta),indent=2)+'\n')
contact=Image.new('RGB',(8*152,9*168),(18,25,33));draw=ImageDraw.Draw(contact)
for i,(m,t) in enumerate(tiles):
 x=(i%8)*152;y=(i//8)*168;contact.paste(t,(x+(152-t.width)//2,y+8),t);draw.text((x+4,y+150),f"{m['key']} {m['row']}/{m['col']}",fill=(240,232,212))
contact.save(A/'sprites_preview.png');print(f'{len(meta)} sprites, {len(raw)} decoded bytes, {n} compressed bytes')
