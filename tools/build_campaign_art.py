#!/usr/bin/env python3
"""Compile supplied reference art into bounded RGB565 runtime assets."""
from pathlib import Path
from PIL import Image,ImageOps
import numpy as np,ctypes,ctypes.util,json,hashlib
R=Path(__file__).resolve().parents[1];S=R/'par/ddr_demo_ti60/embedded_sw/soc/software/standalone/game/src';A=R/'assets/v4'
ref=A/'reference';out=A/'runtime';out.mkdir(exist_ok=True)
lib=ctypes.CDLL(ctypes.util.find_library('lz4'))
lib.LZ4_compressBound.argtypes=[ctypes.c_int];lib.LZ4_compressBound.restype=ctypes.c_int
lib.LZ4_compress_HC.argtypes=[ctypes.c_void_p,ctypes.c_void_p,ctypes.c_int,ctypes.c_int,ctypes.c_int];lib.LZ4_compress_HC.restype=ctypes.c_int
def pack(raw):
 b=ctypes.create_string_buffer(lib.LZ4_compressBound(len(raw)));n=lib.LZ4_compress_HC(raw,b,len(raw),len(b),12);assert n>0;return b.raw[:n]
def rgb565(im):
 a=np.asarray(im.convert('RGB'),dtype=np.uint16);return (((a[:,:,0]>>3)<<11)|((a[:,:,1]>>2)<<5)|(a[:,:,2]>>3)).astype('<u2')
c=['/* Generated by tools/build_campaign_art.py. */','#include <stdint.h>'];manifest=[]
sources=A/'hd_sources'
names=['scene_1_moss_court.png','scene_2_jade_palace.png','scene_3_thunder_city.png','scene_4_ember_palace.png','scene_5_astral_sanctum.png','scene_6_twin_dragon_temple.png']
# On the target the compressed, immutable backgrounds occupy their own DDR
# PT_LOAD region. Native tests keep normal read-only storage.
c+=['#ifdef __riscv','#define BG_ASSET __attribute__((section(".bg_assets"),aligned(64)))','#else','#define BG_ASSET __attribute__((aligned(64)))','#endif']
for i,name in enumerate(names):
 source=sources/name
 im=Image.open(source).convert('RGB')
 width,height=im.size
 if width<1280 or height<720:
  raise ValueError(f'{source}: independent source must be at least 1280x720')
 if abs(width/height-1280/720)>0.03:
  raise ValueError(f'{source}: source must be a wide 16:9 arena, not a collage or square')
 # One direct high-quality conversion to the final size. Never create a
 # 640x360 intermediate, enlarge a small panel, or bake in a dimming rectangle.
 im=im.resize((1280,720),Image.Resampling.LANCZOS)
 im.save(out/f'scene_{i+1}.png');raw=rgb565(im).tobytes();data=pack(raw)
 c+=['const uint8_t v4_bg%d[] BG_ASSET = {'%i]+[','.join(map(str,data[j:j+32]))+',' for j in range(0,len(data),32)]+['};']
 c+=['const unsigned v4_bg%d_size=%d;'%(i,len(data))]
 manifest.append({'scene':i+1,'source':str(source.relative_to(R)),'source_dimensions':[width,height],'source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'runtime_dimensions':[1280,720],'colour_treatment':'source_colours_no_dimming','resampling':'direct_source_to_1280x720_lanczos','raw_bytes':len(raw),'packed_bytes':len(data),'sha256':hashlib.sha256(raw).hexdigest()})
hero_files=['exec-e73cd061-483b-4c8e-b568-4f37d065b8b8.png','exec-e63c3e46-05f1-4b39-adba-af1e56bd59f9.png','exec-b3824cde-9aef-4c8e-b6f1-25c420b03f69.png']
c+=['const uint16_t v4_hero_pixels[3][9][3600]={']
contact=Image.new('RGB',(9*80,3*90),(20,25,35))
for p,name in enumerate(hero_files):
 im=Image.open(ref/name).convert('RGB');scale=im.width/1024;c+=['{']
 for lv in range(9):
  box=(10+lv*112,80,112+lv*112,176)
  tile=im.crop(tuple(round(v*scale) for v in box)).resize((60,60),Image.Resampling.NEAREST)
  ar=np.asarray(tile).copy();dark=ar.max(axis=2)<76
  # Flood only connected background; preserve dark facial features inside sprites.
  stack=[(x,y) for x in range(60) for y in (0,59)]+[(x,y) for y in range(60) for x in (0,59)]
  seen=np.zeros((60,60),dtype=bool)
  while stack:
   x,y=stack.pop()
   if x<0 or y<0 or x>=60 or y>=60 or seen[y,x] or not dark[y,x]:continue
   seen[y,x]=1;stack.extend(((x-1,y),(x+1,y),(x,y-1),(x,y+1)))
  pixels=rgb565(tile);pixels[seen]=0xf81f
  c+=['{']+[','.join(hex(int(v)) for v in row)+',' for row in pixels]+['},']
  ar[seen]=(20,25,35);contact.paste(Image.fromarray(ar),(lv*80+10,p*90+10))
 c+=['},']
c+=['};'];contact.save(out/'heroes_preview.png')
(S/'campaign_art_data.c').write_text('\n'.join(c)+'\n')
(out/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(json.dumps({'backgrounds':6,'heroes':27,'packed_background_bytes':sum(x['packed_bytes'] for x in manifest)}))
