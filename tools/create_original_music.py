#!/usr/bin/env python3
"""Deterministic original chiptune compositions. No external samples or music."""
from pathlib import Path
import argparse, json, math, wave, hashlib
import numpy as np

ROOT=Path(__file__).resolve().parents[1]
GAME=ROOT/'PROJECT/par/ddr_demo_ti60/embedded_sw/soc/software/standalone/game'
SR=32000
TRACKS=[
 ('bgm_title','像素晨光',104,60,'major',[0,2,4,7,6,4,2,1],0),
 ('bgm_menu2','星灯菜单',96,64,'major',[4,6,7,4,2,1,2,0],1),
 ('bgm_stage1','云端疾行',144,62,'dorian',[0,4,2,6,4,7,5,2],2),
 ('bgm_stage2','月下航线',128,57,'minor',[0,2,5,4,2,6,3,1],3),
 ('bgm_boss1','赤色风暴',160,62,'minor',[0,1,4,3,7,4,6,2],4),
 ('bgm_boss2','终幕回响',152,64,'minor',[7,4,6,3,5,2,4,0],5),
 ('bgm_garden','萝卜田野',116,60,'major',[0,2,1,4,2,5,4,1],6),
 ('bgm_garden2','森林夜行',120,55,'major',[4,2,5,6,4,1,2,0],7),
 ('bgm_stress','压力脉冲',150,57,'minor',[0,4,0,6,2,4,1,7],8),
 ('bgm_stress2','数字方阵',138,60,'minor',[0,3,4,2,6,4,7,1],9),
]
SCALES={'major':[0,2,4,5,7,9,11],'minor':[0,2,3,5,7,8,10],'dorian':[0,2,3,5,7,9,10]}
def note_freq(root,degree):
 scale,base=root;octave,index=divmod(degree,7);return 440*2**((base+scale[index]+12*octave-69)/12)
def voice(hz,n,kind,seed):
 t=np.arange(n,dtype=np.float64)/SR;phase=t*hz
 if kind=='lead':x=np.sin(2*np.pi*phase)+.28*np.sin(4*np.pi*phase)+.16*np.sin(6*np.pi*phase)
 elif kind=='arp':x=np.sin(2*np.pi*phase)+.14*np.sin(8*np.pi*phase)
 else:x=2/np.pi*np.arcsin(np.sin(2*np.pi*phase))
 attack=min(n//3,int(.004*SR));release=min(n//3,int(.035*SR));env=np.ones(n)
 env[:attack]=np.linspace(0,1,attack);env[-release:]=np.linspace(1,0,release)
 if kind=='arp':env*=np.exp(-t*10)
 return x*env
def compose(track):
 name,title,bpm,key,mode,motif,seed=track;beat=60/bpm;N=round(32*beat*SR);song=np.zeros(N);rng=np.random.default_rng(9350+seed)
 root=(SCALES[mode],key);progress=[0,5,3,4,0,2,5,4] if mode=='major' else [0,5,2,6,0,3,5,4]
 def add(start,duration,hz,kind,gain):
  at=round(start*beat*SR);n=min(round(duration*beat*SR),N-at)
  if n>0:song[at:at+n]+=gain*voice(hz,n,kind,seed)
 for bar in range(8):
  chord=progress[bar]
  for b in range(4):
   add(bar*4+b,.82,note_freq(root,chord-14),'bass',.20)
   if b in [0,2]:
    at=round((bar*4+b)*beat*SR);n=min(int(.13*SR),N-at);t=np.arange(n)/SR
    song[at:at+n]+=.21*np.sin(2*np.pi*(48*t+40*.035*(1-np.exp(-t/.035))))*np.exp(-t*32)
   if b in [1,3]:
    at=round((bar*4+b)*beat*SR);n=min(int(.09*SR),N-at);t=np.arange(n)/SR;noise=rng.uniform(-1,1,n)
    song[at:at+n]+=.08*noise*np.exp(-t*48)
  for k in range(8):
   degree=chord+[0,2,4,7,4,2,7,2][(k+seed)%8]
   add(bar*4+k*.5,.33,note_freq(root,degree),'arp',.085)
   lead=motif[(k+bar//2)%8]+(7 if bar in [3,7] and k<4 else 0)
   if k not in [(seed+bar)%8]:add(bar*4+k*.5,.38 if k%3 else .75,note_freq(root,lead+7),'lead',.15)
  # A short high-frequency noise hat; deterministic, no sampled material.
  for k in range(8):
   at=round((bar*4+k*.5)*beat*SR);n=min(int(.024*SR),N-at);noise=rng.uniform(-1,1,n);noise-=np.roll(noise,1)
   song[at:at+n]+=.016*noise*np.exp(-np.arange(n)/SR*160)
 edge=min(160,N//20);song[:edge]*=np.linspace(0,1,edge);song[-edge:]*=np.linspace(1,0,edge)
 peak=float(np.max(np.abs(song)));song*=.72/max(peak,1e-9)
 return np.rint(song*32767).astype('<i2')
def main():
 out=GAME/'sound/original_r4';out.mkdir(parents=True,exist_ok=True);records=[]
 for track in TRACKS:
  data=compose(track);p=out/(track[0]+'.wav')
  with wave.open(str(p),'wb') as w:w.setparams((1,2,SR,0,'NONE','not compressed'));w.writeframes(data.tobytes())
  records.append(dict(name=track[0],title=track[1],bpm=track[2],seconds=round(len(data)/SR,3),peak=int(np.max(np.abs(data.astype('int32')))),sha256=hashlib.sha256(p.read_bytes()).hexdigest(),source='Original deterministic composition; generated by tools/create_original_music.py'))
 existing=[]
 for line in (GAME/'sound/demo.txt').read_text().splitlines():
  if line.strip() and not line.startswith('#') and not line.startswith('bgm_'):existing.append(line)
 text='# R4 original chiptune loops; legacy sound effects retained.\n'+'\n'.join(existing)+'\n'
 for name,*_ in TRACKS:text+=f'{name:<15} original_r4/{name}.wav mono loop=auto\n'
 (GAME/'sound/r4_sounds.txt').write_text(text)
 (out/'manifest.json').write_text(json.dumps(records,ensure_ascii=False,indent=2))
 # 3s per song for a quick listening preview, separate from the firmware bank.
 with wave.open(str(out/'preview.wav'),'wb') as w:
  w.setparams((1,2,SR,0,'NONE','not compressed'))
  for track in TRACKS:w.writeframes(compose(track)[:3*SR].tobytes())
 print('Generated',len(records),'original tracks, seconds',round(sum(r['seconds'] for r in records),1))
if __name__=='__main__':main()
